/**
 * A demo's other parts' prop maps (see `usePartControls`): by part, the
 * props it sets itself (left out: they're the demo's, so a control can't
 * silently do nothing). Each prop's options start with `undefined`, so an
 * untouched group changes nothing; parts without options are left out.
 */
export const partPropMaps = (
  parts: Record<string, readonly string[]>,
  addLog: AddLog = () => undefined,
): PartPropMaps =>
  Object.fromEntries(
    Object.entries(parts).flatMap(([part, fixed]) => {
      // (A part's other instances, beside the one a demo features: its
      // options by its name, e.g. `List.Detail (others)`.)
      const options = partOptions[part.replace(/ \([^)]*\)$/u, '')];
      if (!options) return [];

      const propMap = typeof options === 'function' ? options(addLog) : options;
      const entries = Object.entries(propMap)
        .filter(([key]) => !fixed.includes(key))
        .map(
          ([key, values]) =>
            [
              key,
              values[0] === undefined
                ? values
                : [undefined, ...values.filter((value) => value !== undefined)],
            ] as const,
        );

      return entries.length > 0 ? [[part, Object.fromEntries(entries)]] : [];
    }),
  );
